use std::{
    borrow::Cow,
    collections::{BTreeMap, HashMap},
    io::Write,
};

use adif_manip::{
    LengthMode,
    document::{AdifDocument, Field},
    encoding_rs::SHIFT_JIS,
    write,
};
use anyhow::{Context, Result};
use clap::Args;

use crate::core::{
    adif::{AdifInput, LengthCount},
    config::Config,
    output::OutputFile,
};

const DEFAULT_PREAMBLE: &str = concat!("Generated by qso-tools ", env!("CARGO_PKG_VERSION"), "\n");

/// Converts ADIF into ADI with data lengths counted again.
#[derive(Debug, Clone, Args)]
pub struct Arguments {
    #[command(flatten)]
    pub input: AdifInput,

    /// Count data lengths of output in MODE.
    /// shift-jis also encodes output in Shift_JIS.
    #[arg(long, value_name = "MODE", default_value = "bytes")]
    pub length: LengthCount,

    #[command(flatten)]
    pub output: OutputFile,
}

pub fn run(args: Arguments, _config: &Config) -> Result<()> {
    let document = args.input.read()?;

    let text = write_document(&document, args.length.into())?;
    let bytes = match args.length {
        LengthCount::ShiftJis => SHIFT_JIS.encode(&text).0,
        _ => Cow::Borrowed(text.as_bytes()),
    };
    let mut writer = args.output.writer()?;
    writer.write_all(&bytes)?;
    writer.flush()?;

    Ok(())
}

/// Writes header and records of the document in ADI with fields sorted by name.
fn write_document(document: &AdifDocument, length_mode: LengthMode) -> Result<String> {
    let preamble = match document.preamble() {
        p if p.is_empty() || p.contains('<') => DEFAULT_PREAMBLE,
        p => p,
    };
    let mut text = write::header(preamble, sorted_fields(document.headers()), length_mode)
        .context("failed to write header")?;
    for (i, record) in document.records().iter().enumerate() {
        text += &write::record(sorted_fields(record.fields()), length_mode)
            .with_context(|| format!("failed to write record #{}", i + 1))?;
    }
    Ok(text)
}

fn sorted_fields(fields: &HashMap<String, Field>) -> BTreeMap<&str, &str> {
    fields
        .iter()
        .map(|(k, v)| (k.as_str(), v.value()))
        .collect()
}

#[cfg(test)]
mod tests {
    use adif_manip::{read_adi, read_adx};

    use super::*;

    #[test]
    fn writes_document_in_length_mode() {
        let document = read_adi(
            "Exported\n<ADIF_VER:5>3.1.5<EOH>\n<NAME:6>太郎<call:6>JL1HIS<EOR>\n<CALL:4>W1AW<EOR>\n",
            LengthMode::Bytes,
        )
        .unwrap();

        assert_eq!(
            write_document(&document, LengthMode::Codepoints).unwrap(),
            "Exported\n<ADIF_VER:5>3.1.5 <EOH>\n<CALL:6>JL1HIS <NAME:2>太郎 <EOR>\n<CALL:4>W1AW <EOR>\n"
        );
    }

    #[test]
    fn replaces_preamble_read_as_data() {
        let document = read_adx(
            "<ADX><HEADER></HEADER><RECORDS><RECORD><CALL>JL1HIS</CALL></RECORD></RECORDS></ADX>",
        )
        .unwrap();

        let text = write_document(&document, LengthMode::Bytes).unwrap();
        assert_eq!(
            text,
            format!("{DEFAULT_PREAMBLE}<EOH>\n<CALL:6>JL1HIS <EOR>\n")
        );
    }
}
